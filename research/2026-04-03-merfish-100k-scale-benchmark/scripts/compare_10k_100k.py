#!/usr/bin/env python3
"""
compare_10k_100k.py — Side-by-side 10K vs 100K MERFISH benchmark comparison.

Writes results/comparison_table.md relative to the repo root.

Usage:
    python research/2026-04-03-merfish-100k-scale-benchmark/scripts/compare_10k_100k.py
    python research/.../scripts/compare_10k_100k.py --root /path/to/repo
"""
import argparse
import json
from pathlib import Path

METRICS = [
    "trustworthiness", "silhouette", "sna", "procrustes_vs_python",
    "pairwise_corr_vs_python", "spatial_dist_corr", "morans_i_max",
    "chaos", "pas", "ari", "nmi", "celltype_purity", "triplet_accuracy",
    "shepard_pearson", "shepard_spearman", "centroid_dist_corr", "knn_preservation",
]

METHODS = ["python_spectral", "rust_spectral", "random"]
METHOD_LABELS = ["Python", "Rust", "Random"]

TIMING_ROWS = [
    ("preprocessing_s",         "Preprocessing"),
    ("python_spectral_init_s",  "Python spectral init"),
    ("python_sgd_s",            "Python SGD"),
    ("rust_spectral_init_s",    "Rust spectral init"),
    ("rust_init_sgd_s",         "Rust init SGD"),
    ("random_sgd_s",            "Random init SGD"),
    ("metrics_s",               "Metrics computation"),
    ("total_baseline_s",        "Total baseline"),
    ("total_compare_s",         "Total compare"),
]

MEMORY_ROWS = [
    ("peak_rss_baseline_mb", "Baseline phase"),
    ("peak_rss_compare_mb",  "Compare phase"),
    ("rust_peak_rss_mb",     "Rust spectral init"),
]


def _load_json(path: Path):
    """Return parsed JSON dict, or None if file is absent or unreadable."""
    try:
        return json.loads(path.read_text())
    except (FileNotFoundError, json.JSONDecodeError):
        return None


def _parse_rust_perf(path: Path):
    """Parse 'time_s rss_kb' text file → (time_s float, rss_mb float) or (None, None)."""
    try:
        parts = path.read_text().strip().split()
        return float(parts[0]), int(parts[1]) / 1024.0
    except Exception:
        return None, None


def _fmt(val) -> str:
    if val is None:
        return "—"
    if isinstance(val, float):
        return f"{val:.4f}"
    return str(val)


def _md_table(headers: list, rows: list) -> str:
    sep = "|" + "|".join("---" for _ in headers) + "|"
    hdr = "| " + " | ".join(headers) + " |"
    body = "\n".join("| " + " | ".join(str(c) for c in row) + " |" for row in rows)
    return "\n".join([hdr, sep, body])


def build_comparison_table(root: Path) -> str:
    RESULTS = root / "research/2026-04-03-merfish-100k-scale-benchmark/results"
    OUTPUT  = root / "tests/visual_eval/output"

    m10  = _load_json(OUTPUT  / "merfish_10k_metrics.json")
    m100 = _load_json(RESULTS / "merfish_100k_metrics.json")
    t10  = _load_json(OUTPUT  / "merfish_10k_timing.json")
    t100 = _load_json(RESULTS / "merfish_100k_timing.json")
    mem10  = _load_json(OUTPUT  / "merfish_10k_memory.json")
    mem100 = _load_json(RESULTS / "merfish_100k_memory.json")
    rt10_s,  rt10_mb  = _parse_rust_perf(OUTPUT  / "merfish_10k_rust_perf.txt")
    rt100_s, rt100_mb = _parse_rust_perf(RESULTS / "merfish_100k_rust_perf.txt")

    lines = [
        "# MERFISH 100K Scale Benchmark: 10K vs 100K Comparison",
        "",
        "_Generated by `compare_10k_100k.py`_",
        "",
        "---",
        "",
        "## Embedding Quality Metrics",
        "",
    ]

    # 17×6 metric table
    headers = ["Metric", "10K Python", "10K Rust", "10K Random",
               "100K Python", "100K Rust", "100K Random"]
    rows = []
    for metric in METRICS:
        row = [metric]
        for m in (m10, m100):
            for method in METHODS:
                if m is None:
                    row.append("—")
                else:
                    row.append(_fmt(m.get(method, {}).get(metric)))
        rows.append(row)
    lines.append(_md_table(headers, rows))
    lines.append("")

    # Quality gate section
    lines += [
        "---",
        "",
        "## Quality Gate Results (100K)",
        "",
    ]
    if m100:
        rust   = m100.get("rust_spectral", {})
        python = m100.get("python_spectral", {})
        pf     = m100.get("pass_fail", {})

        gate_headers = ["Gate", "Rust", "Python", "Delta / Margin", "Threshold", "Status"]
        gate_rows = []

        tw_r, tw_p = rust.get("trustworthiness"), python.get("trustworthiness")
        if tw_r is not None and tw_p is not None:
            delta = abs(tw_r - tw_p)
            gate_rows.append([
                "|trustworthiness_rust - trustworthiness_python|",
                f"{tw_r:.4f}", f"{tw_p:.4f}", f"{delta:.5f}", "< 0.01",
                pf.get("trustworthiness", "PASS" if delta < 0.01 else "FAIL"),
            ])

        sil_r, sil_p = rust.get("silhouette"), python.get("silhouette")
        if sil_r is not None and sil_p is not None:
            delta = abs(sil_r - sil_p)
            gate_rows.append([
                "|silhouette_rust - silhouette_python|",
                f"{sil_r:.4f}", f"{sil_p:.4f}", f"{delta:.5f}", "< 0.05",
                pf.get("silhouette", "PASS" if delta < 0.05 else "FAIL"),
            ])

        sna_r, sna_p = rust.get("sna"), python.get("sna")
        if sna_r is not None and sna_p is not None:
            margin = sna_r - (sna_p - 0.02)
            gate_rows.append([
                "sna_rust >= sna_python - 0.02",
                f"{sna_r:.6f}", f"{sna_p:.6f}", f"margin={margin:.6f}", ">= 0",
                pf.get("sna", "PASS" if sna_r >= sna_p - 0.02 else "FAIL"),
            ])

        lines.append(_md_table(gate_headers, gate_rows))
        overall = pf.get("overall", "UNKNOWN")
        lines += ["", f"**Overall verdict (100K): {overall}**", ""]
    else:
        lines += ["_(100K metrics unavailable)_", ""]

    # Timing section
    lines += [
        "---",
        "",
        "## Timing (seconds)",
        "",
    ]
    t_rows = [
        [label, _fmt(t10.get(key) if t10 else None), _fmt(t100.get(key) if t100 else None)]
        for key, label in TIMING_ROWS
    ]
    lines.append(_md_table(["Phase", "10K", "100K"], t_rows))
    lines.append("")

    # Memory section
    lines += [
        "---",
        "",
        "## Memory (MB peak RSS)",
        "",
    ]
    mem_rows = [
        [label,
         _fmt(mem10.get(key) if mem10 else None),
         _fmt(mem100.get(key) if mem100 else None)]
        for key, label in MEMORY_ROWS
    ]
    lines.append(_md_table(["Measurement", "10K", "100K"], mem_rows))
    lines.append("")

    # Solver section
    lines += [
        "---",
        "",
        "## Rust Solver Performance",
        "",
        _md_table(
            ["", "10K", "100K"],
            [
                ["Wall time (s)",  _fmt(rt10_s),  _fmt(rt100_s)],
                ["Peak RSS (MB)",  _fmt(rt10_mb), _fmt(rt100_mb)],
            ],
        ),
        "",
    ]

    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(
        description="Generate 10K vs 100K MERFISH comparison table"
    )
    parser.add_argument(
        "--root", default=".",
        help="Repo root directory (default: current working directory)",
    )
    args = parser.parse_args()

    root = Path(args.root).resolve()
    table = build_comparison_table(root)

    out_path = (
        root / "research/2026-04-03-merfish-100k-scale-benchmark/results/comparison_table.md"
    )
    out_path.write_text(table)
    print(f"Wrote {out_path}")

    # Emit the quality gate verdict so CI can grep it
    m100 = _load_json(
        root / "research/2026-04-03-merfish-100k-scale-benchmark/results/merfish_100k_metrics.json"
    )
    if m100:
        pf = m100.get("pass_fail", {})
        verdict = pf.get("overall", m100.get("overall_verdict", "UNKNOWN"))
        print(f"Overall verdict: {verdict}")


if __name__ == "__main__":
    main()
